// フィールドを足せば手を加えなくても検査対象に入る（手書きの一覧は持たない）。
//
// 検査は2方向から掛かる:
//   - test/itemized-copy.test.mjs   … 中身（禁止表現・事実整合）
//   - test/guards.test.mjs          … 書き出したクライアントチャンクに実在するか
//                                     （＝画面から使われずに孤立していないか）
// 文言の制約は lib/copy-rules.mjs を参照。

