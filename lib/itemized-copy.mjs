/**
 * 単位まわり。チップは「候補があることに気づけない」を直すためのもので、
 * 自由入力が主ではなく補助でもなく、同じ `line.unit` への2つの入口。
 * どちらが正か読めるように、可視ラベルを1度だけ置く。
 */
export const UNIT_PICKER = {
  label: "単位",
  // 位置で案内しない。単位の自由入力欄はチップ群の「上」にあり、
  // 広い画面では右上に見えるが、375px 以下では真上に来る（実測の bottom/top:
  // 1280 は 657.2/669.2、375 は 939.8/951.7、320 は 967.0/978.9 で全幅「上」が真）。
  // 「右の欄」は狭い幅で嘘になる。なお左端が揃うのは .matunits コンテナ側で、
  // 先頭チップ自体は可視ラベル「単位」のぶん右へずれる（375 で単位欄 x=71 / チップ x=107）。
  hint: "ほかの単位は上の欄に直接書けます",
  /** チップ群の読み上げ名。材料の通し番号を差し込む。 */
  groupLabel: (index) => `材料 ${index} の単位をえらぶ`,
  // チップ1つぶんの読み上げ名は持たない。可視の文字（cm・m・g・個・枚・ml）が
  // そのまま名前になる。役が radio＝選択肢なので、名前は「cm」という名詞でよく、
  // 「材料 1 の単位を cm にする」という動詞句にすると、群の名前（材料 N の単位を
  // えらぶ）と通し番号が二重に読まれ、しかも選択肢が命令として読み上げられる。
};

